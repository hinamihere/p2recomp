"""Write game/src/nid_table.inc: every import of the EBOOT as {library, nid, name}."""
import sys
sys.path.insert(0, 'tools')
from elfinfo import Prx
import nids

table = nids.load()
out = ['// Generated by tools/gen_nid_table.py from the EBOOT import stubs.']
for lib, attr, funcs in Prx().stubs():
    for nid, stub in funcs:
        name = table[nid][0] if nid in table else f'nid_{nid:08X}'
        out.append(f'{{"{lib}", 0x{nid:08X}u, "{name}"}},')
open('game/src/nid_table.inc', 'w').write('\n'.join(out) + '\n')
print(len(out) - 1, 'imports')
